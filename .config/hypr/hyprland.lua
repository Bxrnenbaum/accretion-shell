local L = require("HyprlandLocal")

hl.config({ autogenerated = false })

local mainMod = "SUPER"

--------------------
--- LOCAL SETUP
--------------------

for _, monitor in ipairs(L.monitors) do
	hl.monitor(monitor)
end

for i = 1, 10 do
	hl.workspace_rule({ workspace = tostring(i), monitor = L.workspaceMonitor })
end

for name, value in pairs(L.env) do
	hl.env(name, value)
end

hl.on("hyprland.start", function()
	for _, cmd in ipairs(L.autostart) do
		hl.exec_cmd(cmd)
	end
end)

hl.config(L.config)

for name, curve in pairs(L.curves) do
	hl.curve(name, curve)
end

for _, animation in ipairs(L.animations) do
	hl.animation(animation)
end

for _, device in ipairs(L.devices) do
	hl.device(device)
end

if hl.plugin.hyprexpo ~= nil then
	hl.config({ plugin = { hyprexpo = L.hyprexpo } })
end

for _, rule in ipairs(L.windowRules) do
	hl.window_rule(rule)
end

for _, rule in ipairs(L.layerRules) do
	hl.layer_rule(rule)
end

--------------------
--- WINDOW RULES
--------------------

hl.window_rule({
	name = "suppress-maximize-events",
	match = { class = ".*" },
	suppress_event = "maximize",
})

hl.window_rule({
	name = "fix-xwayland-drags",
	match = {
		class = "^$",
		title = "^$",
		xwayland = true,
		float = true,
		fullscreen = false,
		pin = false,
	},
	no_focus = true,
})

--------------------
--- KEYBINDINGS
--------------------

hl.gesture({ fingers = 3, direction = "horizontal", action = "workspace" })

-- Cycle layout of the active workspace
hl.bind(mainMod .. " + P", function()
	local layouts = { "scrolling", "dwindle" }
	local workspace = hl.get_active_workspace()
	local next_layout = "dwindle"

	if not workspace then
		return
	end

	for i = 1, #layouts do
		if layouts[i] == workspace.tiled_layout then
			next_layout = layouts[(i % #layouts) + 1]
			break
		end
	end

	hl.workspace_rule({ workspace = workspace.name, layout = next_layout })
end)

